#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# LiteLLM front door for data-parallel (multi-replica) serving.
# Clients keep ONE endpoint (port 8000 = DESKSIDE_BASE_PORT); replicas count up from 8001.
#
#   recipes/lib/litellm.sh render --served NAME --backend 127.0.0.1:8001 --backend 127.0.0.1:8002 [--out FILE]
#   recipes/lib/litellm.sh up     --served NAME --backend ... [--port 8000] [--workers N] [--name deskside-litellm]
#   recipes/lib/litellm.sh down   [--name deskside-litellm]
#
# Config rendered (see ~/.deskside/litellm/config.yaml): one model_name = the served name with every
# replica as a deployment; routing_strategy least-busy (right for long, uneven LLM requests);
# retries + cooldown for a failing replica; pre-call context-window checks; drop_params.
# --num_workers matches the host's cores (capped at 16): a single-worker router capped an
# endpoint near 2.4k tok/s in earlier measurements (recipes/README.md note 2).
# Auth: front door ALWAYS requires a key (current LiteLLM refuses to start without one):
# LITELLM_MASTER_KEY (env, by name) or an auto-generated key in ~/.deskside/litellm/master-key (0600); replicas stay on
# loopback/private ports and are called with DESKSIDE_BACKEND_KEY if they enforce an API key.
# ---------------------------------------------------------------------------
_DSL_LIB="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "${_DSL_LIB}/common.sh"
DS_LITELLM_DIR="${DESKSIDE_LITELLM_DIR:-$HOME/.deskside/litellm}"

ds_litellm_render() {  # served out backends...
  local served="$1" out="$2"; shift 2
  mkdir -p "$(dirname "${out}")"
  {
    echo "# generated by recipes/lib/litellm.sh -- do not hand-edit; re-run the launcher"
    echo "model_list:"
    local b
    for b in "$@"; do
      cat <<Y
  - model_name: ${served}
    litellm_params:
      model: openai/${served}
      api_base: http://${b}/v1
      api_key: os.environ/DESKSIDE_BACKEND_KEY
      timeout: 1800
Y
    done
    cat <<Y
router_settings:
  routing_strategy: least-busy
  num_retries: 2
  timeout: 1800
  cooldown_time: 30
  allowed_fails: 3
  enable_pre_call_checks: true
litellm_settings:
  drop_params: true
  request_timeout: 1800
  num_retries: 2
Y
    if [[ -n "${LITELLM_MASTER_KEY:-}" ]]; then printf 'general_settings:\n  master_key: os.environ/LITELLM_MASTER_KEY\n'; fi
  } > "${out}"
}

# Current LiteLLM refuses to start without a master key (secure default), so the launcher
# always has one: LITELLM_MASTER_KEY if exported, else a random key kept 0600 in the state dir.
# Clients of the front door send it as the API key; probes use it too.
ds_litellm_key() {
  mkdir -p "${DS_LITELLM_DIR}"
  if [[ -z "${LITELLM_MASTER_KEY:-}" ]]; then
    local kf="${DS_LITELLM_DIR}/master-key"
    [[ -s "${kf}" ]] || ( umask 077; echo "sk-$(head -c 24 /dev/urandom | base64 | tr -d '/+=\n')" > "${kf}" )
    LITELLM_MASTER_KEY="$(<"${kf}")"
  fi
  export LITELLM_MASTER_KEY; DS_API_KEY="${LITELLM_MASTER_KEY}"
}

ds_litellm_up() {  # served port workers name backends...
  local served="$1" port="$2" workers="$3" name="$4"; shift 4
  ds_litellm_key
  local cfg="${DS_LITELLM_DIR}/config.yaml" image
  ds_litellm_render "${served}" "${cfg}" "$@"
  image="${DESKSIDE_LITELLM_IMAGE:-$(ds_image litellm)}"
  ds_env_args
  ds_rm "${name}"; ds_pull "${image}"
  local envs=(-e "DESKSIDE_BACKEND_KEY=${DESKSIDE_BACKEND_KEY:-none}")
  if [[ -n "${LITELLM_MASTER_KEY:-}" ]]; then envs+=(-e LITELLM_MASTER_KEY); fi
  ds_docker run -d --restart unless-stopped --name "${name}" --network host \
    "${envs[@]}" -v "${cfg}:/app/config.yaml:ro" "${image}" \
    --config /app/config.yaml --host "${DS_BIND_ADDR}" --port "${port}" --num_workers "${workers}"
}

if [[ "${BASH_SOURCE[0]}" == "$0" ]]; then
  set -euo pipefail
  CMD="${1:-}"; shift || true
  SERVED=""; PORT="${DS_BASE_PORT}"; WORKERS="$(( $(nproc) > 16 ? 16 : $(nproc) ))"; NAME=deskside-litellm; OUT=""; BACKENDS=()
  while [[ $# -gt 0 ]]; do case "$1" in
    --served) SERVED="$2"; shift 2;; --backend) BACKENDS+=("$2"); shift 2;; --port) PORT="$2"; shift 2;;
    --workers) WORKERS="$2"; shift 2;; --name) NAME="$2"; shift 2;; --out) OUT="$2"; shift 2;;
    *) if ds_common_flag "$@"; then shift "${DS_SHIFT}"; else echo "unknown $1" >&2; exit 3; fi;; esac; done
  case "${CMD}" in
    render) : "${SERVED:?--served}"; ds_litellm_render "${SERVED}" "${OUT:-/dev/stdout}" "${BACKENDS[@]}";;
    up) : "${SERVED:?--served}"; (( ${#BACKENDS[@]} )) || { echo "--backend required" >&2; exit 3; }
        ds_litellm_up "${SERVED}" "${PORT}" "${WORKERS}" "${NAME}" "${BACKENDS[@]}"
        DS_MONITORING=0 DS_HEALTH_PATH=/health/liveliness ds_finish "${NAME}" "${PORT}" "${SERVED}" "${NAME}";;
    down) docker rm -f "${NAME}" >/dev/null 2>&1 || true; echo "removed ${NAME}";;
    *) sed -n '2,12p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 3;;
  esac
fi
